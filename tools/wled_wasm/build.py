#!/usr/bin/env python3
"""
Build WLED's effects to WebAssembly for the layout tool (tools/statue_render.html).

    python3 tools/wled_wasm/build.py            # WLED checkout at ../WLED, Emscripten from the emscripten/emsdk Docker image
    WLED_ROOT=/path/to/WLED python3 tools/wled_wasm/build.py

The rule: the simulator runs the firmware's own effect code. FX.cpp, FXparticleSystem.cpp, palettes.cpp, wled_math.cpp
and fastled_slim.cpp are compiled as they are in the checkout; the Segment half of FX_fcn.cpp, FX_2Dfcn.cpp, colors.cpp
and the noise/sound/beat blocks of util.cpp are lifted out at build time (below) with the firmware's bus, file and JSON
plumbing cut away, because those halves cannot compile on a host and carry nothing an effect is judged on. Everything
else the sources need comes from shim/ (a stand-in wled.h, Arduino.h, fcn_declare.h) and sim_main.cpp.
Why: docs/firmware/effects_in_browser.md.
"""
import os, re, subprocess, sys, json

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.environ.get("WLED_ROOT", os.path.join(HERE, "..", "..", "..", "WLED")))
W00 = os.path.join(ROOT, "wled00")
GEN = os.path.join(HERE, "gen")
os.makedirs(GEN, exist_ok=True)


def read(name):
    return open(os.path.join(W00, name), encoding="utf-8", errors="surrogateescape").read()


def write(name, text):
    path = os.path.join(GEN, name)
    prev = open(path, encoding="utf-8", errors="surrogateescape").read() if os.path.exists(path) else None
    if prev != text:
        open(path, "w", encoding="utf-8", errors="surrogateescape").write(text)
        print(f"  gen/{name}: written")
    return path


def span(src, start, end, what):
    i = src.find(start)
    if i < 0: sys.exit(f"build: '{start}' not found ({what}) - has the firmware moved it?")
    j = src.find(end, i)
    if j < 0: sys.exit(f"build: '{end}' not found after '{start}' ({what})")
    return i, j


def function_end(src, start_marker):
    """Index just past the closing brace of the top-level function that begins at start_marker."""
    i = src.find(start_marker)
    if i < 0: sys.exit(f"build: '{start_marker}' not found")
    j = src.find("\n}\n", i)
    return j + 3


HEAD = "// GENERATED by tools/wled_wasm/build.py from the WLED checkout - do not edit; edit the firmware.\n"


def gen_segment():
    """The Segment half of FX_fcn.cpp: everything before WS2812FX::finalizeInit(). Its bus-capability scan is replaced
    (the simulator has no busses: every pixel is RGB), the rest is the firmware's."""
    src = read("FX_fcn.cpp")
    i, j = span(src, "#include", "void WS2812FX::finalizeInit()", "Segment methods")
    body = src[i:j]
    a = body.find("void Segment::refreshLightCapabilities() const {")
    if a < 0: sys.exit("build: refreshLightCapabilities not found")
    b = body.find("\n}\n", a) + 3
    body = body[:a] + "void Segment::refreshLightCapabilities() const { _capabilities = isActive() ? SEG_CAPABILITY_RGB : 0; } // sim: no busses\n" + body[b:]
    write("fx_fcn_segment.cpp", HEAD + body)
    # the palette names the UI lists, from the same file the firmware serves them from
    key = "const char JSON_palette_names[] PROGMEM = R\"=====("
    a = src.find(key)
    b = src.find(")=====\";", a)
    if a < 0 or b < 0: sys.exit("build: JSON_palette_names not found")
    names = json.loads(src[a + len(key):b])
    write("palette_names.h", HEAD + "const char JSON_palette_names[] PROGMEM = R\"=====(" + json.dumps(names) + ")=====\";\n")


def gen_2d():
    """FX_2Dfcn.cpp without WS2812FX::setUpMatrix() (it reads the ledmap file); the drawing helpers are the firmware's."""
    src = read("FX_2Dfcn.cpp")
    i = src.find("void WS2812FX::setUpMatrix()")
    if i < 0: sys.exit("build: setUpMatrix not found")
    j = function_end(src, "void WS2812FX::setUpMatrix()")
    write("fx_2d.cpp", HEAD + src[:i] + src[j:])


def gen_util():
    """The functions of util.cpp the effects call, lifted whole: the metadata-defaults parser, the beat generators, the
    sound simulator (with its enum), the random helpers and the Perlin noise. Verbatim, so the noise field and the beats
    are the firmware's."""
    src = read("util.cpp")
    def fn(start): return src[src.find(start):function_end(src, start)]
    def fn_to(start, last): return src[src.find(start):function_end(src, last)]
    sim = src.find("um_data_t* simulateSound(uint8_t simulationId)")
    enum = src.rfind("typedef enum", 0, sim)
    if min(sim, enum) < 0: sys.exit("build: simulateSound not found in util.cpp")
    parts = [src[src.find("#define UTF8_LEN"):function_end(src, "size_t utf8_strlen(const char *s)")],
             fn("int16_t extractModeDefaults(uint8_t mode, const char *segVar)"),
             fn_to("uint16_t beat88(uint16_t beats_per_minute_88, uint32_t timebase)", "uint8_t beatsin8_t(uint16_t beats_per_minute"),
             src[enum:function_end(src, "um_data_t* simulateSound(uint8_t simulationId)")],
             fn_to("uint8_t get_random_wheel_index(uint8_t pos)", "int32_t hw_random(int32_t lowerlimit, int32_t upperlimit)"),
             src[src.find("#define PERLIN_SHIFT"):function_end(src, "uint8_t perlin8(uint16_t x, uint16_t y, uint16_t z)")]]
    write("util_fx.cpp", HEAD + '#include "wled.h"\n#include "fcn_declare.h"\n\n' + "\n\n".join(parts))


def gen_colors():
    """colors.cpp with loadCustomPalettes() emptied: it reads palette files through ArduinoJson."""
    src = read("colors.cpp")
    i, j = span(src, "void loadCustomPalettes() {", "size_t removeUsermodPalettes", "loadCustomPalettes")
    write("colors_sim.cpp", HEAD + src[:i] + "void loadCustomPalettes() {} // sim: no palette files\n\n" + src[j:])


def main():
    if not os.path.isdir(W00): sys.exit(f"build: no WLED checkout at {ROOT} (set WLED_ROOT)")
    print(f"WLED checkout: {ROOT}")
    gen_segment(); gen_2d(); gen_util(); gen_colors()
    sources = [os.path.join(HERE, "sim_main.cpp"),
               os.path.join(GEN, "fx_fcn_segment.cpp"), os.path.join(GEN, "fx_2d.cpp"), os.path.join(GEN, "util_fx.cpp"), os.path.join(GEN, "colors_sim.cpp"),
               os.path.join(W00, "FX.cpp"), os.path.join(W00, "FXparticleSystem.cpp"), os.path.join(W00, "palettes.cpp"),
               os.path.join(W00, "wled_math.cpp"), os.path.join(W00, "fontmanager.cpp"),
               os.path.join(W00, "src", "dependencies", "fastled_slim", "fastled_slim.cpp")]
    includes = [os.path.join(HERE, "shim"), W00, GEN, os.path.join(W00, "src", "dependencies", "fastled_slim")]
    out = os.path.join(HERE, "wled_fx.js")
    build = os.path.join(HERE, "build"); os.makedirs(build, exist_ok=True)
    flags = ["-std=gnu++17", "-O2", "-fno-exceptions", "-Wno-everything", "-ferror-limit=40", "-include", os.path.join(HERE, "shim", "wled.h")]
    for d in includes: flags += ["-I", d]
    # Emscripten from the emscripten/emsdk Docker image unless em++ is on PATH: nothing to install on the machine.
    # The image sees the common parent of this folder and the WLED checkout as /work.
    import shutil
    docker = shutil.which("em++") is None
    common = os.path.commonpath([HERE, ROOT])
    remap = (lambda p: "/work" + os.path.abspath(p)[len(common):]) if docker else (lambda p: p)
    def run(args):
        args = [remap(a) if a.startswith("/") else a for a in args]
        if docker: args = ["docker", "run", "--rm", "-v", f"{common}:/work", "-w", remap(HERE), "emscripten/emsdk:latest"] + args
        r = subprocess.run(args, capture_output=True, text=True)
        log = (r.stdout or "") + (r.stderr or "")
        if r.returncode != 0: print(log[-12000:]); sys.exit(f"build FAILED ({r.returncode})")
        return log
    # one object per source, rebuilt only when the source (or a shim/gen file) is newer: FX.cpp alone takes a while
    deps = max(os.path.getmtime(os.path.join(r, f)) for d in (os.path.join(HERE, "shim"), GEN) for r, _, fs in os.walk(d) for f in fs)
    objs = []
    for src in sources:
        obj = os.path.join(build, os.path.basename(src) + ".o"); objs.append(obj)
        if os.path.exists(obj) and os.path.getmtime(obj) > max(os.path.getmtime(src), deps): continue
        print(f"  compiling {os.path.basename(src)}")
        extra = ["-DSIM_MAIN"] if src.endswith("sim_main.cpp") else []
        run(["em++"] + flags + extra + ["-c", src, "-o", obj])
    print("  linking")
    log = run(["em++", "-O2"] + objs + ["-o", out,
               "-s", "EXPORTED_RUNTIME_METHODS=ccall,cwrap,UTF8ToString,HEAPU8,HEAPU32",
               "-s", "ALLOW_MEMORY_GROWTH=1", "-s", "MODULARIZE=1", "-s", "EXPORT_NAME=WledFx",
               # one file with the wasm embedded, so the page still works opened as a file:// (fetch() of a .wasm is refused there);
               # node included so tools/wled_wasm/test.js can sweep every effect
               # base64 rather than Emscripten's raw byte string: the file stays text (diffable, publishable as an artifact file)
               "-s", "SINGLE_FILE=1", "-s", "SINGLE_FILE_BINARY_ENCODE=0", "-s", "ENVIRONMENT=web,node"])
    if log.strip(): print(log[-3000:])
    print(f"  wled_fx.js: {os.path.getsize(out):,} bytes")
    print("build OK")


if __name__ == "__main__":
    main()
